# 算数运算符: +, -, *, /, //, %, ** (优先级: ** ---> *, /, //, % ---> +, -)
print(10 // 3)      # //是整除
print(10 ** 3)      # **是幂指数

# 赋值运算符: =, +=, -=, *=, /=, //=, %=, **=
a = 10
a /= 10
print(a, type(a))   # 除法除出来是浮点数

# 比较运算符: ==, !=, >. <. >=, <=
print("1000不等于2000吗?", 1000 != 2000)

# 逻辑运算符: and, or, not
print("把True取反是:", not True)

a = int(input("请输入一个数字: "))
print("这个数字在0-100之间:", a >= 0 and a <= 100)